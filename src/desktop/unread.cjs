// Подсчёт непрочитанных и решение, показывать ли уведомление.
//
// Счётчик берётся из заголовка вкладки: мессенджеры пишут туда «(3) WhatsApp».
//
// Раньше уведомление не показывалось, если предыдущее значение счётчика было
// нулём. Условие поставили, чтобы при запуске не сыпались уведомления обо всём,
// что накопилось до открытия приложения — но заодно оно глушило и настоящий
// переход «было пусто, пришло первое сообщение». Для чата, где ждут заявку,
// это ровно тот случай, который важнее всего.
//
// Правильное различие — не «ноль или не ноль», а «видели ли мы этот счётчик
// вообще». Первое значение после загрузки страницы становится точкой отсчёта,
// всё последующее — настоящие изменения.

function extractUnreadCount(title = "") {
  const match = String(title).match(/^\((\d+)\)/);
  return match ? Number(match[1]) : 0;
}

function shouldNotifyAboutUnread({
  hasBaseline = false,
  previous = 0,
  next = 0,
  hadRecentPreview = false
} = {}) {
  // Первое значение после загрузки — это то, что накопилось раньше.
  if (!hasBaseline) {
    return false;
  }

  // Счётчик не вырос: сообщения прочитали или заголовок обновился без изменений.
  if (next <= previous) {
    return false;
  }

  // Об этом сообщении уже рассказал мост превью — второе уведомление лишнее.
  if (hadRecentPreview) {
    return false;
  }

  return true;
}

module.exports = {
  extractUnreadCount,
  shouldNotifyAboutUnread
};
